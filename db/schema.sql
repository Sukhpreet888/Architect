-- ARCHFLOW schema (PostgreSQL / Supabase).
-- Tables live in their own "archflow" schema, which Supabase does not expose through its public Data API.
-- Row Level Security is enabled with no policies, so the anon/authenticated API roles can never read them;
-- the app server connects as the table owner (postgres) and is unaffected.
CREATE SCHEMA IF NOT EXISTS archflow;
CREATE TABLE IF NOT EXISTS archflow.users (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, email TEXT UNIQUE NOT NULL, name TEXT NOT NULL, password_hash TEXT NOT NULL,
  email_verified INTEGER NOT NULL DEFAULT 0, verify_token TEXT, reset_token TEXT, reset_expires TEXT,
  created_at text NOT NULL DEFAULT to_char(now() AT TIME ZONE 'utc', 'YYYY-MM-DD HH24:MI:SS')
);
CREATE TABLE IF NOT EXISTS archflow.orgs (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL, address TEXT, phone TEXT, website TEXT,
  currency TEXT NOT NULL DEFAULT 'INR', timezone TEXT NOT NULL DEFAULT 'Asia/Kolkata', area_unit TEXT NOT NULL DEFAULT 'sqft',
  invoice_prefix TEXT NOT NULL DEFAULT 'INV', billing_email TEXT,
  plan TEXT, plan_status TEXT NOT NULL DEFAULT 'trial', trial_ends_at TEXT NOT NULL,
  custom_users INTEGER, custom_projects INTEGER, custom_storage_mb INTEGER,
  extra_users INTEGER NOT NULL DEFAULT 0, extra_projects INTEGER NOT NULL DEFAULT 0, extra_storage_mb INTEGER NOT NULL DEFAULT 0,
  card_last4 TEXT, card_brand TEXT, next_billing_date TEXT,
  created_at text NOT NULL DEFAULT to_char(now() AT TIME ZONE 'utc', 'YYYY-MM-DD HH24:MI:SS')
);
CREATE TABLE IF NOT EXISTS archflow.memberships (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, org_id INTEGER NOT NULL REFERENCES archflow.orgs(id) ON DELETE CASCADE,
  user_id INTEGER NOT NULL REFERENCES archflow.users(id) ON DELETE CASCADE, role TEXT NOT NULL,
  active INTEGER NOT NULL DEFAULT 1, created_at text NOT NULL DEFAULT to_char(now() AT TIME ZONE 'utc', 'YYYY-MM-DD HH24:MI:SS'), UNIQUE(org_id, user_id)
);
CREATE TABLE IF NOT EXISTS archflow.invites (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, org_id INTEGER NOT NULL REFERENCES archflow.orgs(id) ON DELETE CASCADE, email TEXT NOT NULL, name TEXT,
  role TEXT NOT NULL, token TEXT UNIQUE NOT NULL, invited_by INTEGER, accepted_at TEXT,
  created_at text NOT NULL DEFAULT to_char(now() AT TIME ZONE 'utc', 'YYYY-MM-DD HH24:MI:SS')
);
CREATE TABLE IF NOT EXISTS archflow.billing_events (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, org_id INTEGER NOT NULL REFERENCES archflow.orgs(id) ON DELETE CASCADE, kind TEXT NOT NULL,
  description TEXT NOT NULL, amount double precision NOT NULL DEFAULT 0, status TEXT NOT NULL, created_at text NOT NULL DEFAULT to_char(now() AT TIME ZONE 'utc', 'YYYY-MM-DD HH24:MI:SS')
);
CREATE TABLE IF NOT EXISTS archflow.templates (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, org_id INTEGER NOT NULL REFERENCES archflow.orgs(id) ON DELETE CASCADE, family_id INTEGER, name TEXT NOT NULL,
  version INTEGER NOT NULL DEFAULT 1, body TEXT NOT NULL, is_current INTEGER NOT NULL DEFAULT 1, notes TEXT,
  created_by INTEGER, created_at text NOT NULL DEFAULT to_char(now() AT TIME ZONE 'utc', 'YYYY-MM-DD HH24:MI:SS')
);
CREATE TABLE IF NOT EXISTS archflow.projects (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, org_id INTEGER NOT NULL REFERENCES archflow.orgs(id) ON DELETE CASCADE, code TEXT NOT NULL, name TEXT NOT NULL,
  client_name TEXT, client_email TEXT, client_phone TEXT, location TEXT, description TEXT,
  type TEXT NOT NULL, subtype TEXT, plot_area double precision, built_up_area double precision, area_unit TEXT,
  start_date TEXT, end_date TEXT, scope TEXT NOT NULL DEFAULT 'design', template_id INTEGER, manager_id INTEGER,
  contract_value double precision, construction_budget double precision NOT NULL DEFAULT 0,
  status TEXT NOT NULL DEFAULT 'active', closure_report TEXT, closed_at TEXT, created_by INTEGER,
  created_at text NOT NULL DEFAULT to_char(now() AT TIME ZONE 'utc', 'YYYY-MM-DD HH24:MI:SS')
);
CREATE TABLE IF NOT EXISTS archflow.project_members (
  project_id INTEGER NOT NULL REFERENCES archflow.projects(id) ON DELETE CASCADE, user_id INTEGER NOT NULL REFERENCES archflow.users(id) ON DELETE CASCADE,
  PRIMARY KEY(project_id, user_id)
);
CREATE TABLE IF NOT EXISTS archflow.phases (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, project_id INTEGER NOT NULL REFERENCES archflow.projects(id) ON DELETE CASCADE, seq INTEGER NOT NULL, name TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'not_started', planned_start TEXT, planned_end TEXT, started_at TEXT, completed_at TEXT
);
CREATE TABLE IF NOT EXISTS archflow.subphases (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, phase_id INTEGER NOT NULL REFERENCES archflow.phases(id) ON DELETE CASCADE, name TEXT NOT NULL, seq INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS archflow.deliverables (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, project_id INTEGER NOT NULL REFERENCES archflow.projects(id) ON DELETE CASCADE,
  phase_id INTEGER REFERENCES archflow.phases(id) ON DELETE CASCADE, subphase_id INTEGER REFERENCES archflow.subphases(id) ON DELETE SET NULL,
  name TEXT NOT NULL, status TEXT NOT NULL DEFAULT 'pending', due_date TEXT, created_at text NOT NULL DEFAULT to_char(now() AT TIME ZONE 'utc', 'YYYY-MM-DD HH24:MI:SS')
);
CREATE TABLE IF NOT EXISTS archflow.tasks (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, project_id INTEGER NOT NULL REFERENCES archflow.projects(id) ON DELETE CASCADE,
  phase_id INTEGER REFERENCES archflow.phases(id) ON DELETE SET NULL, subphase_id INTEGER REFERENCES archflow.subphases(id) ON DELETE SET NULL,
  deliverable_id INTEGER REFERENCES archflow.deliverables(id) ON DELETE SET NULL,
  title TEXT NOT NULL, description TEXT, assignee_id INTEGER REFERENCES archflow.users(id) ON DELETE SET NULL,
  start_date TEXT, due_date TEXT, priority TEXT NOT NULL DEFAULT 'medium', status TEXT NOT NULL DEFAULT 'todo',
  progress INTEGER NOT NULL DEFAULT 0, depends_on INTEGER REFERENCES archflow.tasks(id) ON DELETE SET NULL, source TEXT,
  created_by INTEGER, completed_at TEXT, created_at text NOT NULL DEFAULT to_char(now() AT TIME ZONE 'utc', 'YYYY-MM-DD HH24:MI:SS')
);
CREATE TABLE IF NOT EXISTS archflow.documents (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, project_id INTEGER NOT NULL REFERENCES archflow.projects(id) ON DELETE CASCADE,
  phase_id INTEGER REFERENCES archflow.phases(id) ON DELETE SET NULL, title TEXT NOT NULL, category TEXT,
  task_id INTEGER REFERENCES archflow.tasks(id) ON DELETE SET NULL, deliverable_id INTEGER REFERENCES archflow.deliverables(id) ON DELETE SET NULL,
  restricted INTEGER NOT NULL DEFAULT 0, created_by INTEGER, created_at text NOT NULL DEFAULT to_char(now() AT TIME ZONE 'utc', 'YYYY-MM-DD HH24:MI:SS')
);
CREATE TABLE IF NOT EXISTS archflow.document_versions (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, document_id INTEGER NOT NULL REFERENCES archflow.documents(id) ON DELETE CASCADE, version INTEGER NOT NULL,
  stored_name TEXT NOT NULL, original_name TEXT NOT NULL, mime TEXT, size bigint NOT NULL DEFAULT 0, notes TEXT,
  uploaded_by INTEGER, created_at text NOT NULL DEFAULT to_char(now() AT TIME ZONE 'utc', 'YYYY-MM-DD HH24:MI:SS')
);
CREATE TABLE IF NOT EXISTS archflow.approvals (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, project_id INTEGER NOT NULL REFERENCES archflow.projects(id) ON DELETE CASCADE,
  phase_id INTEGER REFERENCES archflow.phases(id) ON DELETE SET NULL, deliverable_id INTEGER REFERENCES archflow.deliverables(id) ON DELETE SET NULL,
  document_id INTEGER REFERENCES archflow.documents(id) ON DELETE SET NULL, type TEXT NOT NULL DEFAULT 'design', title TEXT NOT NULL,
  description TEXT, status TEXT NOT NULL DEFAULT 'draft', round INTEGER NOT NULL DEFAULT 1, requested_by INTEGER,
  requested_at TEXT, decided_at TEXT, created_at text NOT NULL DEFAULT to_char(now() AT TIME ZONE 'utc', 'YYYY-MM-DD HH24:MI:SS')
);
CREATE TABLE IF NOT EXISTS archflow.approval_reviewers (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, approval_id INTEGER NOT NULL REFERENCES archflow.approvals(id) ON DELETE CASCADE,
  user_id INTEGER NOT NULL REFERENCES archflow.users(id) ON DELETE CASCADE, decision TEXT, comment TEXT, decided_at TEXT,
  UNIQUE(approval_id, user_id)
);
CREATE TABLE IF NOT EXISTS archflow.approval_history (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, approval_id INTEGER NOT NULL REFERENCES archflow.approvals(id) ON DELETE CASCADE, round INTEGER NOT NULL,
  user_id INTEGER, action TEXT NOT NULL, comment TEXT, created_at text NOT NULL DEFAULT to_char(now() AT TIME ZONE 'utc', 'YYYY-MM-DD HH24:MI:SS')
);
CREATE TABLE IF NOT EXISTS archflow.invoices (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, org_id INTEGER NOT NULL REFERENCES archflow.orgs(id) ON DELETE CASCADE,
  project_id INTEGER NOT NULL REFERENCES archflow.projects(id) ON DELETE CASCADE, number TEXT NOT NULL, milestone TEXT NOT NULL,
  amount double precision NOT NULL, tax double precision NOT NULL DEFAULT 0, issue_date TEXT, due_date TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'draft', notes TEXT, created_by INTEGER, created_at text NOT NULL DEFAULT to_char(now() AT TIME ZONE 'utc', 'YYYY-MM-DD HH24:MI:SS')
);
CREATE TABLE IF NOT EXISTS archflow.payments (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, invoice_id INTEGER NOT NULL REFERENCES archflow.invoices(id) ON DELETE CASCADE, amount double precision NOT NULL,
  paid_on TEXT NOT NULL, method TEXT NOT NULL, reference TEXT, proof_name TEXT, proof_original TEXT, proof_size bigint NOT NULL DEFAULT 0,
  recorded_by INTEGER, created_at text NOT NULL DEFAULT to_char(now() AT TIME ZONE 'utc', 'YYYY-MM-DD HH24:MI:SS')
);
CREATE TABLE IF NOT EXISTS archflow.expenditures (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, project_id INTEGER NOT NULL REFERENCES archflow.projects(id) ON DELETE CASCADE, category TEXT NOT NULL,
  description TEXT NOT NULL, vendor TEXT, amount double precision NOT NULL, spent_on TEXT NOT NULL, invoice_ref TEXT,
  status TEXT NOT NULL DEFAULT 'pending', decided_by INTEGER, created_by INTEGER, created_at text NOT NULL DEFAULT to_char(now() AT TIME ZONE 'utc', 'YYYY-MM-DD HH24:MI:SS')
);
CREATE TABLE IF NOT EXISTS archflow.suppliers (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, org_id INTEGER NOT NULL REFERENCES archflow.orgs(id) ON DELETE CASCADE, name TEXT NOT NULL,
  contact TEXT, email TEXT, phone TEXT, created_at text NOT NULL DEFAULT to_char(now() AT TIME ZONE 'utc', 'YYYY-MM-DD HH24:MI:SS')
);
CREATE TABLE IF NOT EXISTS archflow.materials (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, project_id INTEGER NOT NULL REFERENCES archflow.projects(id) ON DELETE CASCADE, name TEXT NOT NULL,
  unit TEXT NOT NULL DEFAULT 'nos', stock double precision NOT NULL DEFAULT 0, reorder_level double precision NOT NULL DEFAULT 0,
  supplier_id INTEGER REFERENCES archflow.suppliers(id) ON DELETE SET NULL, created_at text NOT NULL DEFAULT to_char(now() AT TIME ZONE 'utc', 'YYYY-MM-DD HH24:MI:SS')
);
CREATE TABLE IF NOT EXISTS archflow.material_txns (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, material_id INTEGER NOT NULL REFERENCES archflow.materials(id) ON DELETE CASCADE, kind TEXT NOT NULL,
  qty double precision NOT NULL, unit_cost double precision NOT NULL DEFAULT 0, txn_date TEXT NOT NULL, note TEXT,
  expenditure_id INTEGER REFERENCES archflow.expenditures(id) ON DELETE SET NULL, created_by INTEGER,
  created_at text NOT NULL DEFAULT to_char(now() AT TIME ZONE 'utc', 'YYYY-MM-DD HH24:MI:SS')
);
CREATE TABLE IF NOT EXISTS archflow.site_visits (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, project_id INTEGER NOT NULL REFERENCES archflow.projects(id) ON DELETE CASCADE, visit_date TEXT NOT NULL,
  purpose TEXT NOT NULL, assigned_to INTEGER REFERENCES archflow.users(id) ON DELETE SET NULL, status TEXT NOT NULL DEFAULT 'scheduled',
  report TEXT, completed_at TEXT, created_by INTEGER, created_at text NOT NULL DEFAULT to_char(now() AT TIME ZONE 'utc', 'YYYY-MM-DD HH24:MI:SS')
);
CREATE TABLE IF NOT EXISTS archflow.site_issues (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, project_id INTEGER NOT NULL REFERENCES archflow.projects(id) ON DELETE CASCADE,
  visit_id INTEGER REFERENCES archflow.site_visits(id) ON DELETE SET NULL, title TEXT NOT NULL, description TEXT,
  severity TEXT NOT NULL DEFAULT 'medium', status TEXT NOT NULL DEFAULT 'open', task_id INTEGER REFERENCES archflow.tasks(id) ON DELETE SET NULL,
  created_by INTEGER, created_at text NOT NULL DEFAULT to_char(now() AT TIME ZONE 'utc', 'YYYY-MM-DD HH24:MI:SS')
);
CREATE TABLE IF NOT EXISTS archflow.reminders_sent (
  entity TEXT NOT NULL, entity_id INTEGER NOT NULL, rkey TEXT NOT NULL, sent_at text NOT NULL DEFAULT to_char(now() AT TIME ZONE 'utc', 'YYYY-MM-DD HH24:MI:SS'),
  PRIMARY KEY(entity, entity_id, rkey)
);
CREATE TABLE IF NOT EXISTS archflow.email_log (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, org_id INTEGER, to_email TEXT NOT NULL, subject TEXT NOT NULL, category TEXT,
  body_html TEXT, status TEXT NOT NULL, error TEXT, created_at text NOT NULL DEFAULT to_char(now() AT TIME ZONE 'utc', 'YYYY-MM-DD HH24:MI:SS')
);
CREATE TABLE IF NOT EXISTS archflow.cost_budgets (
  project_id INTEGER NOT NULL REFERENCES archflow.projects(id) ON DELETE CASCADE, category TEXT NOT NULL,
  amount double precision NOT NULL DEFAULT 0, PRIMARY KEY(project_id, category)
);
CREATE INDEX IF NOT EXISTS ix_tasks_project ON archflow.tasks(project_id);
CREATE INDEX IF NOT EXISTS ix_tasks_assignee ON archflow.tasks(assignee_id);
CREATE INDEX IF NOT EXISTS ix_invoices_org ON archflow.invoices(org_id);
CREATE INDEX IF NOT EXISTS ix_projects_org ON archflow.projects(org_id);
CREATE INDEX IF NOT EXISTS ix_email_org ON archflow.email_log(org_id);
